import Data.List (maximumBy, minimumBy, sortBy, sort)
import Data.Ord (comparing)
data T = T Double deriving (Eq, Ord, Show)
data U = U Int Double deriving (Eq, Ord, Show)
newtype N = N Double deriving (Eq, Ord, Show)
data C = C { cv :: Int, ct :: Char } deriving Show
instance Eq C where a == b = cv a == cv b
instance Ord C where compare a b = compare (cv a) (cv b)
main :: IO ()
main = do
  print (max 0.0 (-0.0 :: Double), min 0.0 (-0.0 :: Double))
  print (max (-0.0) (0.0 :: Double), min (-0.0) (0.0 :: Double))
  print (max (0.0::Float) (-0.0), min (0.0::Float) (-0.0))
  print (max [0.0] [-0.0 :: Double], min [0.0] [-0.0 :: Double])
  print (max (Just 0.0) (Just (-0.0 :: Double)), min (Just 0.0) (Just (-0.0::Double)))
  print (max (0.0,1::Int) (-0.0,1), min (0.0,1::Int) (-0.0,1))
  print (max (T 0.0) (T (-0.0)), min (T 0.0) (T (-0.0)))
  print (max (U 1 0.0) (U 1 (-0.0)), min (U 1 0.0) (U 1 (-0.0)))
  print (max (N 0.0) (N (-0.0)), min (N 0.0) (N (-0.0)))
  print (max (C 1 'a') (C 1 'b'), min (C 1 'a') (C 1 'b'))
  print (max [C 1 'a'] [C 1 'b'], min [C 1 'a'] [C 1 'b'])
  print (max (Just (C 1 'a')) (Just (C 1 'b')), min (Just (C 1 'a')) (Just (C 1 'b')))
  print (max (C 1 'a', 'z') (C 1 'b', 'z'))
  print (maximum [C 1 'a', C 1 'b', C 0 'c'], minimum [C 1 'a', C 1 'b', C 2 'c'])
  print (maximum [0.0, -0.0 :: Double], minimum [-0.0, 0.0 :: Double])
  print (maximumBy (comparing cv) [C 1 'a', C 1 'b'], minimumBy (comparing cv) [C 1 'a', C 1 'b'])
  print (maximum (Just (C 1 'a')), maximum [[C 1 'a'], [C 1 'b']])
  print (sort [C 1 'b', C 1 'a', C 0 'z'])
  print (max (Left (C 1 'a')) (Left (C 1 'b') :: Either C Int))
  print (max (EQ) EQ, max 'a' 'a', max (1::Integer) 1)
